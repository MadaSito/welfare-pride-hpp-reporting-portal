    driver: bridge
COMPOSE
  # Private user-defined network, NOT internal:true: Caddy needs outbound ACME.
  # There are no app ports or host networking; only proxy 80/443 is published.
  chmod 600 "$COMPOSE_FILE"
  COMPOSE_CREATED=1
}
write_bootstrap_compose() {
  # Attaching Docker stdout to a terminal alone does NOT disable daemon logs.
  # A separate one-off service config disables logging and restarts completely.
  cat > "$CONFIG_DIR/bootstrap.compose.yaml" <<COMPOSE
services:
