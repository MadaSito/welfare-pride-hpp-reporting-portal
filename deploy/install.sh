#!/usr/bin/env bash
# Fresh-server, synthetic-data-only installer. Never run against an existing portal.
# Do not invoke with bash -x, script(1), a recording terminal, or credential logging.
set +x
set -Eeuo pipefail
umask 077
export LC_ALL=C
export PATH=/usr/sbin:/usr/bin:/sbin:/bin

readonly APP_DIR=/opt/welfare-pride-portal
readonly DATA_DIR=/var/lib/welfare-pride-portal/data
readonly CONFIG_DIR=/etc/welfare-pride-portal
readonly RUNTIME_FILE=$CONFIG_DIR/runtime.env
readonly COMPOSE_FILE=$CONFIG_DIR/compose.yaml
readonly APP_USER=portal
readonly NODE_DIR=/opt/welfare-pride-node
readonly APP_UNIT=welfare-pride-portal.service
readonly PROXY_UNIT=welfare-pride-portal-caddy.service
readonly REPO_URL=https://github.com/MadaSito/welfare-pride-hpp-reporting-portal.git
readonly PNPM_VERSION=10.4.1
METHOD= DOMAIN= ADMIN_EMAIL= REF= RESOLVED_SHA=
CHECK=0 ACK=0 APP_CREATED=0 PROXY_CREATED=0 COMPOSE_CREATED=0
INSTALL_STARTED=0 OS_ID= OS_VERSION= OS_CODENAME= ARCH= TTY_FD=

log() { printf '%s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
usage() {
  cat <<'USAGE'
Welfare Pride portal — NEW SERVER / SYNTHETIC DATA ONLY
Usage: sudo bash deploy/install.sh [options]
  --method=vps|baremetal|docker     Native VPS recommended; prompts if omitted
  --domain=portal.example.org      Required HTTPS DNS hostname, never an IP
  --email=admin@example.org        Required initial administrator email
  --ref=FULL_40_HEX_COMMIT          Optional immutable source commit
  --acknowledge-testing-only       Required, including with --check
  --check                         Read-only host preflight, no packages/files/services
  -h, --help                      Show this help without requiring root

Supported: Ubuntu 22.04/24.04, Debian 12/13; amd64/arm64; systemd.
Native uses Node 22, pnpm 10.4.1, SQLite and Caddy HTTPS. Docker publishes
ONLY Caddy 80/443; the app and SQLite remain on a private container network.
A private /dev/tty is mandatory for installation. The administrator password
is generated by the helper process and displayed ONCE there, before startup.
No reinstall, reset, overwrite, skip-admin, HTTP or no-Caddy options exist.
HTTPS needs DNS directed to this VPS and reachable public ACME validation;
an entirely internal VPS needs an organization-managed TLS/DNS-challenge plan
outside this installer. No HTTP or unnoticed self-signed fallback is provided.
USAGE
}
parse_args() {
  local arg
  for arg in "$@"; do
    case "$arg" in
      --method=*) METHOD=${arg#*=} ;;
      --domain=*) DOMAIN=${arg#*=} ;;
      --email=*) ADMIN_EMAIL=${arg#*=} ;;
      --ref=*) REF=${arg#*=}; [[ -n "$REF" ]] || die '--ref cannot be empty.' ;;
      --acknowledge-testing-only) ACK=1 ;;
      --check) CHECK=1 ;;
      -h|--help) usage; exit 0 ;;
      *) die "Unknown option: $arg (see --help)." ;;
    esac
  done
}
validate_input() {
  [[ "$ACK" == 1 ]] || die 'Require --acknowledge-testing-only. NOT approved for real/sensitive data.'
  [[ -n "$DOMAIN" ]] || die 'Require --domain=HTTPS-DNS-HOSTNAME.'
  DOMAIN=${DOMAIN,,}
  [[ ${#DOMAIN} -le 253 && "$DOMAIN" == *.* && "$DOMAIN" != *..* ]] || die 'Invalid domain: supply a real DNS hostname, not an IP or localhost.'
  [[ "$DOMAIN" =~ ^[a-z0-9.-]+$ && "$DOMAIN" =~ \.[a-z]{2,63}$ ]] || die 'Invalid domain: no schemes, ports, paths, IPs or config characters.'
  case "$DOMAIN" in
    localhost|*.localhost|*.local|*.internal|*.invalid|*.test|*.example|*.home.arpa|example.com|*.example.com|example.org|*.example.org|example.net|*.example.net)
      die 'Use a real domain you control, not a reserved/internal/example hostname.' ;;
  esac
  local label
  local -a labels
  IFS=. read -r -a labels <<< "$DOMAIN"
  for label in "${labels[@]}"; do
    [[ ${#label} -ge 1 && ${#label} -le 63 && "$label" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?$ ]] || die 'Invalid DNS label.'
  done
  [[ ${#ADMIN_EMAIL} -le 254 && "$ADMIN_EMAIL" =~ ^[A-Za-z0-9._%+-]+@[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?\.[A-Za-z]{2,63}$ && "$ADMIN_EMAIL" != *..* && "$ADMIN_EMAIL" != .* && "$ADMIN_EMAIL" != *.@* ]] || die 'Require a valid --email=admin@your-domain (simple ASCII mailbox).'
  [[ -z "$REF" || "$REF" =~ ^[a-fA-F0-9]{40}$ ]] || die '--ref must be a full 40-character hexadecimal commit SHA.'
  [[ -z "$METHOD" || "$METHOD" == vps || "$METHOD" == baremetal || "$METHOD" == docker ]] || die '--method must be vps, baremetal or docker.'
}
private_tty() {
  # Root may write another user's terminal after sudo; actual confidentiality is
  # the operator's responsibility. Refuse no-TTY, group/world-readable or recorder.
  [[ -z "${BASH_XTRACEFD:-}" ]] || die 'Disable xtrace/logging before installation.'
  exec {TTY_FD}<> /dev/tty || die 'Require a private interactive /dev/tty (SSH with a TTY); never record bootstrap output.'
  [[ -t "$TTY_FD" ]] || die '/dev/tty is not an interactive terminal.'
  local terminal mode
  terminal=$(tty <&"$TTY_FD")
  mode=$(stat -Lc '%a' "$terminal")
  (( (8#$mode & 0044) == 0 )) || die 'Terminal is readable by other users. Use a private SSH session.'
  printf 'Use a PRIVATE, UNRECORDED terminal. Do not use tee, script(1), screen recording or session credential capture.\n' >&"$TTY_FD"
}
select_method() {
  [[ -z "$METHOD" ]] || return 0
  [[ -n "$TTY_FD" ]] || private_tty
  printf 'Choose deployment: 1) VPS/native systemd (recommended) 2) bare metal/native systemd 3) Docker\nSelect [1/2/3]: ' >&"$TTY_FD"
  local choice
  read -r choice <&"$TTY_FD"
  case "$choice" in
    1) METHOD=vps ;;
    2) METHOD=baremetal ;;
    3) METHOD=docker ;;
    *) die 'Invalid selection; pass --method=vps|baremetal|docker.' ;;
  esac
}
path_absent() { [[ ! -e "$1" && ! -L "$1" ]] || die "Fresh-server refusal: already exists: $1"; }
unit_absent() {
  local unit=$1 state
  state=$(systemctl show "$unit" --property=LoadState --value) || die "Unable to inspect systemd unit $unit."
  [[ "$state" == not-found ]] || die "Fresh-server refusal: existing systemd unit $unit ($state)."
}
ports_free() {
  local listeners
  listeners=$(ss -H -lntu) || die 'Unable to inspect occupied ports.'
  if awk '$5 ~ /:(80|443|3000)$/ {found=1} END {exit !found}' <<< "$listeners"; then
    die 'Fresh-server refusal: TCP/UDP 80, 443 or 3000 is occupied. Do not stop existing services automatically.'
  fi
}
check_docker_conflicts() {
  local pkg installed
  for pkg in docker.io docker-compose docker-compose-v2 podman-docker containerd runc; do
    if installed=$(dpkg-query -W -f='${db:Status-Status}' "$pkg" 2>/dev/null); then
      [[ "$installed" != installed ]] || die "Conflicting existing package $pkg. Installer will not uninstall it; use a new server."
    fi
  done
}
preflight() {
  [[ "$EUID" == 0 ]] || die 'Run as root on a NEW server (sudo bash deploy/install.sh ...).'
  [[ -f /etc/os-release ]] || die 'Cannot identify supported OS.'
  # os-release is trusted host configuration, not remotely supplied shell input.
  . /etc/os-release
  OS_ID=${ID:-}; OS_VERSION=${VERSION_ID:-}; OS_CODENAME=${VERSION_CODENAME:-}
  case "$OS_ID:$OS_VERSION" in
    ubuntu:22.04|ubuntu:24.04|debian:12|debian:13) ;;
    *) die 'Supported ONLY Ubuntu 22.04/24.04 or Debian 12/13.' ;;
  esac
  ARCH=$(dpkg --print-architecture)
  [[ "$ARCH" == amd64 || "$ARCH" == arm64 ]] || die 'Supported architectures: amd64 and arm64.'
  [[ -d /run/systemd/system ]] || die 'A booted systemd server is required; not a container/chroot.'
  local cmd path unit
  for cmd in apt-get apt-cache dpkg-query systemctl ss awk stat getent install runuser; do
    command -v "$cmd" >/dev/null || die "Preflight requires $cmd already available."
  done
  for path in "$APP_DIR" /var/lib/welfare-pride-portal "$DATA_DIR" "$CONFIG_DIR" "$RUNTIME_FILE" \
    /etc/caddy /var/lib/caddy /etc/systemd/system/"$APP_UNIT" /etc/systemd/system/"$PROXY_UNIT"; do
    path_absent "$path"
  done
  for unit in "$APP_UNIT" "$PROXY_UNIT" caddy.service caddy-api.service; do unit_absent "$unit"; done
  if getent passwd "$APP_USER" >/dev/null; then die "Existing user $APP_USER; use a new server."; fi
  if getent group "$APP_USER" >/dev/null; then die "Existing group $APP_USER; use a new server."; fi
  command -v caddy >/dev/null && die 'Existing Caddy binary; installer will not reuse or overwrite it.'
  ports_free
  if [[ "$METHOD" == docker ]]; then
    if command -v docker >/dev/null; then
      docker compose version >/dev/null || die 'Existing Docker lacks Compose v2; installer will not modify it.'
      docker info >/dev/null || die 'Existing Docker engine is not usable.'
      local names
      names=$(docker ps -a --format '{{.Names}}')
      [[ -z "$names" ]] || die 'Docker already contains containers; use a dedicated new server.'
      names=$(docker network ls --format '{{.Name}}')
      [[ "$names" != *welfare-pride* ]] || die 'Existing portal Docker network.'
      names=$(docker volume ls --format '{{.Name}}')
      [[ "$names" != *welfare-pride* ]] || die 'Existing portal Docker volume.'
    else
      check_docker_conflicts
      path_absent /etc/apt/sources.list.d/docker.sources
      path_absent /etc/apt/sources.list.d/docker.list
      path_absent /etc/apt/keyrings/docker.asc
    fi
  else
    path_absent "$NODE_DIR"
  fi
  log "Preflight OK: $OS_ID $OS_VERSION / $ARCH; method=$METHOD; fixed installation paths absent; ports free."
  log "HTTPS hostname: $DOMAIN. DNS/ACME reachability is verified only during installation; --check does not contact it."
  log 'SQLite only; unresolved README security blockers. SYNTHETIC DATA ONLY; no real credentials/integrations.'
}
cleanup_on_exit() {
  local rc=$?
  trap - EXIT
  if (( rc != 0 && INSTALL_STARTED == 1 )); then
    printf 'Installation failed. Stopping ONLY newly created portal services; preserving all files/data/secrets.\n' >&2
    # Cleanup failures are reported explicitly, not disguised as success.
    if [[ "$COMPOSE_CREATED" == 1 ]]; then
      if ! compose stop; then printf 'WARNING: unable to stop portal containers; restrict network exposure immediately.\n' >&2; fi
    fi
    if [[ "$PROXY_CREATED" == 1 ]]; then
      if ! systemctl disable --now "$PROXY_UNIT"; then printf 'WARNING: could not stop new proxy unit.\n' >&2; fi
    fi
    if [[ "$APP_CREATED" == 1 ]]; then
      if ! systemctl disable --now "$APP_UNIT"; then printf 'WARNING: could not stop new app unit.\n' >&2; fi
    fi
    printf 'Do NOT rerun installer or delete/reset data. See deploy/INSTALL.md for manual, reviewed recovery.\n' >&2
  fi
  exit "$rc"
}
trap cleanup_on_exit EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

apt_dependencies() {
  export DEBIAN_FRONTEND=noninteractive
  apt-get update
  apt-get install -y --no-install-recommends ca-certificates curl git openssl gnupg python3 xz-utils
  if [[ "$METHOD" != docker ]]; then
    apt-get install -y --no-install-recommends build-essential pkg-config
  fi
}
fetch_https() { curl --proto '=https' --tlsv1.2 --fail --show-error --silent --connect-timeout 15 --max-time 300 "$@"; }
clone_source() {
  # If this script lives in a Git checkout, default to its installed commit.
  # A downloaded standalone script resolves main once and records its full SHA.
  local script_dir
  script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
  if [[ -z "$REF" && -d "$script_dir/../.git" ]]; then
    REF=$(git -C "$script_dir/.." rev-parse HEAD)
  fi
  log 'Fetching public application source from GitHub; no GitHub token or credentials required.'
  export GIT_TERMINAL_PROMPT=0
  git clone --no-checkout "$REPO_URL" "$APP_DIR"
  if [[ -n "$REF" ]]; then
    git -C "$APP_DIR" fetch origin "$REF"
    git -C "$APP_DIR" checkout --detach "$REF"
  else
    git -C "$APP_DIR" checkout --detach origin/main
  fi
  RESOLVED_SHA=$(git -C "$APP_DIR" rev-parse HEAD)
  [[ "$RESOLVED_SHA" =~ ^[a-f0-9]{40}$ ]] || die 'Invalid resolved source SHA.'
  [[ -z "$REF" || "${REF,,}" == "$RESOLVED_SHA" ]] || die 'Source commit does not match requested ref.'
  [[ -f "$APP_DIR/server/install-admin.ts" && -f "$APP_DIR/pnpm-lock.yaml" ]] || die 'Source lacks secure installation helper/lockfile. Use the reviewed installer-compatible commit.'
  printf '%s\n' "$RESOLVED_SHA" > "$CONFIG_DIR/source-commit"
  printf '%s\n' "$METHOD" > "$CONFIG_DIR/install-method"
  chown -R root:root "$APP_DIR"
  chmod -R go-w "$APP_DIR"
  log "Resolved application source: $RESOLVED_SHA"
}
write_runtime() {
  local data_path=$DATA_DIR bind=127.0.0.1
  [[ "$METHOD" != docker ]] || { data_path=/app/data; bind=0.0.0.0; }
  path_absent "$RUNTIME_FILE"
  # No password is ever generated or stored by the shell. Runtime encryption/session
  # material is generated directly into the private file, never echoed/logged.
  set -o noclobber
  {
    printf 'NODE_ENV=production\nPORT=3000\nBIND_ADDRESS=%s\nHOST=%s\nAPP_ORIGIN=https://%s\n' "$bind" "$bind" "$DOMAIN"
    printf 'APP_SESSION_SECRET='; openssl rand -hex 48 || die 'Session-secret generation failed.'
    printf 'APP_ENCRYPTION_KEY='; openssl rand -base64 32 || die 'Encryption-key generation failed.'
    printf 'AUDIT_HASH_SALT='; openssl rand -hex 32 || die 'Audit-salt generation failed.'
    printf 'DATA_DIR=%s\nSESSION_COOKIE_NAME=__Host-wp_session\nREQUIRE_LOCAL_MFA=true\n' "$data_path"
  } > "$RUNTIME_FILE" || die 'Unable to create private runtime file.'
  set +o noclobber
  chown root:root "$RUNTIME_FILE"
  chmod 600 "$RUNTIME_FILE"
}
install_node() {
  local node_arch=x64 version archive expected
  [[ "$ARCH" != arm64 ]] || node_arch=arm64
  install -d -m 700 "$CONFIG_DIR/downloads"
  fetch_https https://nodejs.org/dist/index.json -o "$CONFIG_DIR/downloads/node-index.json"
  version=$(python3 - "$CONFIG_DIR/downloads/node-index.json" <<'PY'
import json, re, sys
versions = [v['version'] for v in json.load(open(sys.argv[1])) if re.fullmatch(r'v22\.\d+\.\d+', v['version']) and v.get('lts')]
if not versions: raise SystemExit('No official Node 22 LTS release found')
print(max(versions, key=lambda s: tuple(map(int, s[1:].split('.')))))
PY
)
  [[ "$version" =~ ^v22\.[0-9]+\.[0-9]+$ ]] || die 'Invalid official Node version.'
  archive="node-$version-linux-$node_arch.tar.xz"
  fetch_https "https://nodejs.org/dist/$version/SHASUMS256.txt" -o "$CONFIG_DIR/downloads/SHASUMS256.txt"
  fetch_https "https://nodejs.org/dist/$version/$archive" -o "$CONFIG_DIR/downloads/$archive"
  expected=$(awk -v f="$archive" '$2 == f {print $1}' "$CONFIG_DIR/downloads/SHASUMS256.txt")
  [[ "$expected" =~ ^[a-f0-9]{64}$ ]] || die 'Missing/unambiguous official SHA256 checksum.'
  (cd "$CONFIG_DIR/downloads" && printf '%s  %s\n' "$expected" "$archive" | sha256sum --check --strict -)
  install -d -m 755 "$NODE_DIR"
  tar -xJf "$CONFIG_DIR/downloads/$archive" -C "$NODE_DIR" --strip-components=1 --no-same-owner
  export PATH="$NODE_DIR/bin:/usr/sbin:/usr/bin:/sbin:/bin"
  [[ $(node --version) == "$version" ]] || die 'Installed Node version mismatch.'
  npm install --global --prefix "$NODE_DIR" --ignore-scripts "pnpm@$PNPM_VERSION"
  [[ $(pnpm --version) == "$PNPM_VERSION" ]] || die 'pnpm version mismatch.'
  printf '%s\n' "$version" > "$CONFIG_DIR/node-version"
}
build_native() {
  (
    cd "$APP_DIR"
    # Preserve the checked-out workspace/patches/overrides. Install skips every
    # lifecycle script, then explicit rebuild permits only better-sqlite3.
    pnpm --config.manage-package-manager-versions=false install --frozen-lockfile --ignore-scripts
    pnpm --config.manage-package-manager-versions=false '--config.onlyBuiltDependencies[]=better-sqlite3' rebuild better-sqlite3
    pnpm --config.manage-package-manager-versions=false run build
    [[ -f dist/index.js ]] || die 'Native build missing dist/index.js.'
  )
  chown -R root:root "$APP_DIR" "$NODE_DIR"
  chmod -R go-w "$APP_DIR" "$NODE_DIR"
  # Code must be readable/traversable, not writable, by the unprivileged runtime.
  chmod -R a+rX "$APP_DIR" "$NODE_DIR"
}
bootstrap_native() {
  log 'Creating administrator OFFLINE. Password is shown once directly on your private terminal; save it in your password manager.'
  (
    cd "$APP_DIR"
    # Load only root-generated secrets in this subprocess without shell tracing.
    unset SQLITE_PATH COOKIE_INSECURE NODE_OPTIONS NODE_PATH
    set -a
    . "$RUNTIME_FILE"
    set +a
    runuser -u "$APP_USER" -- "$NODE_DIR/bin/node" --import tsx server/install-admin.ts --email "$ADMIN_EMAIL" < /dev/tty > /dev/tty 2> /dev/tty
  )
  verify_offline_native
}
verify_offline_native() {
  # Read-only verification; never print password hashes or modify credentials.
  python3 - "$DATA_DIR/portal.db" "$ADMIN_EMAIL" <<'PY'
import sqlite3, sys
c = sqlite3.connect('file:' + sys.argv[1] + '?mode=ro', uri=True)
rows = c.execute('SELECT email,role,status,mfa_required,must_change_password,auth_provider,tenant_id FROM users').fetchall()
if len(rows) != 1: raise SystemExit('Offline bootstrap verification: expected exactly one user')
u = rows[0]
if u[0].lower() != sys.argv[2].lower() or u[1:6] != ('super_admin','active',1,1,'local') or not u[6]:
    raise SystemExit('Offline bootstrap verification failed; refusing startup')
c.close()
PY
}
install_caddy() {
  local candidate
  candidate=$(apt-cache policy caddy | awk '/Candidate:/ {print $2}')
  if [[ -z "$candidate" || "$candidate" == '(none)' ]]; then
    path_absent /usr/share/keyrings/caddy-stable-archive-keyring.gpg
    path_absent /etc/apt/sources.list.d/caddy-stable.list
    fetch_https https://dl.cloudsmith.io/public/caddy/stable/gpg.key -o "$CONFIG_DIR/downloads/caddy-key.asc"
    gpg --batch --dearmor --output /usr/share/keyrings/caddy-stable-archive-keyring.gpg "$CONFIG_DIR/downloads/caddy-key.asc"
    chmod 644 /usr/share/keyrings/caddy-stable-archive-keyring.gpg
    printf 'deb [signed-by=/usr/share/keyrings/caddy-stable-archive-keyring.gpg] https://dl.cloudsmith.io/public/caddy/stable/deb/debian any-version main\n' > /etc/apt/sources.list.d/caddy-stable.list
    chmod 644 /etc/apt/sources.list.d/caddy-stable.list
    apt-get update
  fi
  # The packaged service normally autostarts a demo HTTP site. Mask only these
  # preflight-absent units, without touching any existing policy-rc.d or services.
  # Runtime masks expire on reboot; the package unit remains disabled below.
  systemctl mask --runtime caddy.service caddy-api.service
  apt-get install -y --no-install-recommends caddy
  systemctl disable caddy.service
}
write_caddyfile() {
  local upstream=$1
  cat > "$CONFIG_DIR/Caddyfile" <<CADDY
{
    email $ADMIN_EMAIL
    admin off
}
$DOMAIN {
    reverse_proxy $upstream {
        header_up -CF-Connecting-IP
        header_up -CF-IPCountry
        header_up -CF-Ray
        header_up -True-Client-IP
        header_up -X-Real-IP
        header_up -Forwarded
        header_up X-Forwarded-For {remote_host}
        header_up X-Forwarded-Proto {scheme}
        header_up X-Forwarded-Host {host}
    }
}
CADDY
  chmod 600 "$CONFIG_DIR/Caddyfile"
}
write_native_units() {
  # Config directory is root-private; Caddy receives a systemd-managed credential
  # instead of requiring its service account to read arbitrary runtime secrets.
  cat > /etc/systemd/system/"$APP_UNIT" <<UNIT
[Unit]
Description=Welfare Pride portal (synthetic-data testing only)
After=network.target
[Service]
Type=simple
User=$APP_USER
Group=$APP_USER
WorkingDirectory=$APP_DIR
EnvironmentFile=$RUNTIME_FILE
ExecStart=$NODE_DIR/bin/node $APP_DIR/dist/index.js
Restart=on-failure
RestartSec=5
UMask=0077
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
ReadWritePaths=$DATA_DIR
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectControlGroups=true
RestrictSUIDSGID=true
CapabilityBoundingSet=
StandardOutput=journal
StandardError=journal
LogRateLimitIntervalSec=30s
LogRateLimitBurst=500
[Install]
WantedBy=multi-user.target
UNIT
  APP_CREATED=1
  cat > /etc/systemd/system/"$PROXY_UNIT" <<UNIT
[Unit]
