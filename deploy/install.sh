User=caddy
Group=caddy
LoadCredential=Caddyfile:$CONFIG_DIR/Caddyfile
ExecStart=/usr/bin/caddy run --config %d/Caddyfile --adapter caddyfile
Restart=on-failure
RestartSec=5
Environment=HOME=/var/lib/caddy
Environment=XDG_DATA_HOME=/var/lib/caddy
Environment=XDG_CONFIG_HOME=/var/lib/caddy
UMask=0077
AmbientCapabilities=CAP_NET_BIND_SERVICE
CapabilityBoundingSet=CAP_NET_BIND_SERVICE
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
ReadWritePaths=/var/lib/caddy
StandardOutput=journal
StandardError=journal
LogRateLimitIntervalSec=30s
LogRateLimitBurst=500
[Install]
WantedBy=multi-user.target
UNIT
  PROXY_CREATED=1
  chmod 644 /etc/systemd/system/"$APP_UNIT" /etc/systemd/system/"$PROXY_UNIT"
  systemctl daemon-reload
}
install_native() {
  useradd --system --user-group --shell /usr/sbin/nologin --home-dir "$APP_DIR" "$APP_USER"
  install -d -o "$APP_USER" -g "$APP_USER" -m 700 "$DATA_DIR"
  install_node
  build_native
  bootstrap_native
  install_caddy
  write_caddyfile 127.0.0.1:3000
  caddy validate --config "$CONFIG_DIR/Caddyfile" --adapter caddyfile
  write_native_units
  ports_free
  systemctl enable --now "$APP_UNIT"
  wait_native_health
  systemctl enable --now "$PROXY_UNIT"
}
install_docker_engine() {
  if command -v docker >/dev/null; then return 0; fi
  install -d -m 755 /etc/apt/keyrings
  fetch_https "https://download.docker.com/linux/$OS_ID/gpg" -o /etc/apt/keyrings/docker.asc
  chmod 644 /etc/apt/keyrings/docker.asc
  [[ "$OS_CODENAME" =~ ^[a-z]+$ ]] || die 'Missing supported distribution codename.'
  cat > /etc/apt/sources.list.d/docker.sources <<APT
Types: deb
URIs: https://download.docker.com/linux/$OS_ID
Suites: $OS_CODENAME
Components: stable
Architectures: $ARCH
Signed-By: /etc/apt/keyrings/docker.asc
APT
  chmod 644 /etc/apt/sources.list.d/docker.sources
  apt-get update
  apt-get install -y --no-install-recommends docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
  systemctl enable --now docker.service
  docker compose version
  docker info >/dev/null
}
compose() { docker compose --project-name welfare-pride-portal --file "$COMPOSE_FILE" "$@"; }
write_compose() {
  cat > "$COMPOSE_FILE" <<COMPOSE
services:
  app:
    build:
      context: $APP_DIR
      dockerfile: Dockerfile
    image: welfare-pride-portal:$RESOLVED_SHA
    user: "10001:10001"
    env_file:
      - $RUNTIME_FILE
    restart: unless-stopped
    init: true
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - ALL
    volumes:
      - type: bind
        source: $DATA_DIR
        target: /app/data
        bind:
          create_host_path: false
    networks:
      - portal
    logging:
      driver: json-file
      options:
        max-size: "10m"
        max-file: "5"
  caddy:
    image: caddy:2.10.2-alpine
    restart: unless-stopped
    ports:
      - "80:80"
      - "443:443"
    volumes:
      - $CONFIG_DIR/Caddyfile:/etc/caddy/Caddyfile:ro
      - $CONFIG_DIR/caddy-data:/data
      - $CONFIG_DIR/caddy-config:/config
    networks:
      - portal
    logging:
      driver: json-file
      options:
        max-size: "10m"
        max-file: "5"
networks:
