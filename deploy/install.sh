install_docker() {
  install_docker_engine
  install -d -o 10001 -g 10001 -m 700 "$DATA_DIR"
  install -d -m 700 "$CONFIG_DIR/caddy-data" "$CONFIG_DIR/caddy-config"
  write_caddyfile app:3000
  [[ -f "$APP_DIR/Dockerfile" ]] || die 'Reviewed source lacks Dockerfile.'
  write_compose
  compose config --quiet
  compose build app
  compose pull caddy
  # The one-off bootstrap has a TTY and no service restart loop; no published
  # app ports and no proxy exist at this point. NEVER pipe/capture its output.
  log 'Creating administrator OFFLINE in a one-off container. Save password shown once on private terminal.'
  write_bootstrap_compose
  docker compose --project-name welfare-pride-portal --file "$CONFIG_DIR/bootstrap.compose.yaml" config --quiet
  docker compose --project-name welfare-pride-portal --file "$CONFIG_DIR/bootstrap.compose.yaml" run --rm --no-deps --interactive app node --import tsx server/install-admin.ts --email "$ADMIN_EMAIL" < /dev/tty > /dev/tty 2> /dev/tty
  verify_offline_native
  ports_free
  compose up -d app
  wait_docker_health
  compose up -d caddy
}
json_health() { python3 -c 'import json,sys; x=json.load(sys.stdin); sys.exit(0 if x.get("status")=="ok" and x.get("database")=="sqlite" else 1)'; }
json_setup_closed() { python3 -c 'import json,sys; x=json.load(sys.stdin); sys.exit(0 if x.get("setupNeeded") is False and isinstance(x.get("userCount"),int) and x["userCount"] >= 1 else 1)'; }
http_get() { curl --noproxy '*' --proto '=https,http' --fail --silent --show-error --connect-timeout 5 --max-time 10 "$1"; }
wait_native_health() {
  local i
  for ((i=1; i<=60; i++)); do
    if http_get http://127.0.0.1:3000/api/v1/health 2>/dev/null | json_health 2>/dev/null; then
      http_get http://127.0.0.1:3000/api/v1/auth/setup/status | json_setup_closed
      return 0
    fi
    sleep 2
  done
  die 'Native health timeout; proxy not started. Inspect app journal.'
}
wait_docker_health() {
  local i
  for ((i=1; i<=60; i++)); do
    if compose exec -T app node --input-type=module -e 'const r=await fetch("http://127.0.0.1:3000/api/v1/health"); const x=await r.json(); if(!r.ok||x.status!=="ok"||x.database!=="sqlite") process.exit(1)' >/dev/null 2>&1; then
      compose exec -T app node --input-type=module -e 'const r=await fetch("http://127.0.0.1:3000/api/v1/auth/setup/status"); const x=await r.json(); if(!r.ok||x.setupNeeded!==false||!(x.userCount>=1)) process.exit(1)'
      return 0
    fi
    sleep 2
  done
  die 'Docker health timeout; proxy not started. Inspect app container logs.'
}
verify_https() {
  log 'Waiting up to five minutes for trusted public HTTPS and closed setup status (no insecure TLS fallback).'
  local deadline=$((SECONDS + 300))
  while (( SECONDS < deadline )); do
    if http_get "https://$DOMAIN/api/v1/health" 2>/dev/null | json_health 2>/dev/null; then
      http_get "https://$DOMAIN/api/v1/auth/setup/status" | json_setup_closed
      log 'Validated: SQLite health status=ok and setupNeeded=false over verified HTTPS.'
      return 0
    fi
    sleep 5
  done
  die 'HTTPS validation failed: verify DNS A/AAAA, TCP 80/443, ACME reachability, and logs. Newly created portal services will be stopped.'
}
